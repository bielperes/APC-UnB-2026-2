#Atv 03 – Soma (revisita ao LMC). Leia dois inteiros e mostre a soma,
# a diferença e o produto, um por linha. 

primeiro_numero = int(input("Primeiro número: "))
segundo_numero = int(input("Segundo número: "))

soma = primeiro_numero + segundo_numero
print(soma)

diferenca = primeiro_numero - segundo_numero
print(diferenca)

produto = primeiro_numero * segundo_numero
print(produto)
